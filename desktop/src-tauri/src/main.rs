/// Default web admin port in cc-connect ([management] port, mirrors cmd web.go).
const DEFAULT_WEB_PORT: u16 = 9820;

/// Placeholder-free bootstrap config written by the shell on first launch.
/// The engine's own bootstrap template contains an unusable project (placeholder
/// work_dir → engine exits fatally), so the shell owns its own valid default:
/// an acp agent with a stub command the web UI later replaces.
const DEFAULT_CONFIG_TOML: &str = r#"# cc-connect — automatically generated by CC Connect.app
# After modifying, save and click "Restart Service" in the menu Config Editor to take effect.

[log]
level = "info"

[[projects]]
name = "my-project"
work_dir = "~"

[projects.agent]
type = "acp"
[projects.agent.options]
# placeholder: please change to the real agent CLI in the web UI, e.g. /opt/homebrew/bin/claude
cmd = "/usr/bin/true"

[[projects.platforms]]
type = "cloud_web"
[projects.platforms.options]
# placeholder: only used to let the service start; please replace it with real values after configuring IM platforms
token = "placeholder-connect-token-randomized-生成时替换"
ws_url = "ws://127.0.0.1:9/ws"

[management]
enabled = true
"#;

/// Write the shell's default config when none exists yet.
/// Returns true when a fresh default was created (used to trigger first-run setup).
fn write_default_config_if_missing(config_path: &std::path::Path) -> bool {
    if config_path.exists() {
        return false;
    }
    if let Some(dir) = config_path.parent() {
        let _ = std::fs::create_dir_all(dir);
    }
    let _ = std::fs::write(config_path, DEFAULT_CONFIG_TOML.replace(
        "placeholder-connect-token-randomized-生成时替换",
        &random_token(),
    ));
    true
}

/// True while the config still points at the shell-initial acp stub, i.e. the
/// user has not picked a real agent CLI yet.
fn agent_is_stub(config_path: &std::path::Path) -> bool {
    std::fs::read_to_string(config_path)
        .map(|c| c.contains("cmd = \"/usr/bin/true\""))
        .unwrap_or(true)
}

/// Generate a random 24-hex-char token without pulling a rand dependency:
/// mixes pid, nanosecond clock and stack address entropy, run through xorshift.
fn random_token() -> String {
    let anchor = 0u8;
    let mut s = std::process::id() as u64
        ^ std::time::SystemTime::now().duration_since(std::time::UNIX_EPOCH)
            .map(|d| d.as_nanos() as u64)
            .unwrap_or(0)
        ^ (&anchor as *const _ as u64);
    let mut out = String::with_capacity(24);
    for _ in 0..6 {
        s ^= s << 13;
        s ^= s >> 7;
        s ^= s << 17;
        out.push_str(&format!("{:08x}", s as u32));
    }
    out
}

/// How long to wait for the engine's web UI to accept TCP connections.
const ENGINE_START_TIMEOUT: Duration = Duration::from_secs(45);
/// Short first-attempt window: if the engine is alive but slow, attempt 2
/// retries to the full timeout instead of failing the app outright.
const FAST_START_TIMEOUT: Duration = Duration::from_secs(8);

/// State holding the spawned cc-connect engine process.
struct Engine {
    child: MutChild,
}

/// PID of the live engine, mirrored for the atexit reaper (see register_reaper).
static ENGINE_PID: std::sync::atomic::AtomicU32 = std::sync::atomic::AtomicU32::new(0);

/// atexit reaper: every normal exit path (window close, menu quit, teardown)
/// must not leave the engine running on 127.0.0.1. SIGKILL of the shell is
/// covered next launch via the engine's per-config --force lock.
extern "C" fn reap_engine_at_exit() {
    let pid = ENGINE_PID.load(std::sync::atomic::Ordering::Relaxed);
    if pid != 0 {
        unsafe { libc::kill(pid as i32, libc::SIGKILL) };
    }
}

/// Register the atexit reaper once at startup.
fn register_reaper() {
    unsafe { libc::atexit(reap_engine_at_exit) };
}

/// Clear the reaper marker after a deliberate engine kill (kill + wait reaped).
fn clear_reaper_pid() {
    ENGINE_PID.store(0, std::sync::atomic::Ordering::Relaxed);
}

/// Last engine startup error, surfaced in the editor window.
struct StartupError(StdMutex<Option<String>>);

/// Resolved paths for the engine config and log, in the OS app-config dir.
struct ConfigPaths {
    config: PathBuf,
    log: PathBuf,
}

#[derive(Deserialize)]
struct ManagementCfg {
    port: Option<u16>,
    token: Option<String>,
}

/// Read mgmt port+token from the config file; missing/invalid parts fall back gracefully.
fn read_management(config_path: &std::path::Path) -> (u16, Option<String>) {
    let cfg: Option<ManagementCfg> = std::fs::read_to_string(config_path)
        .ok()
        .and_then(|s| toml::from_str::<toml::Value>(&s).ok())
        .and_then(|v| v.get("management").cloned())
        .and_then(|m| m.try_into().ok());
    match cfg {
        Some(c) => (
            // port = 0 (e.g. saved by the web settings UI) means "unset" to the
            // engine, which then falls back to the default port; the shell must
            // do the same or it points the webview at an invalid port.
            c.port.filter(|p| *p != 0).unwrap_or(DEFAULT_WEB_PORT),
            c.token.filter(|t| !t.is_empty()),
        ),
        None => (DEFAULT_WEB_PORT, None),
    }
}

/// Wait until {port} accepts TCP connections, or return false on timeout.
/// Stops early when the engine process has exited (won't ever listen again).
fn wait_for_port(port: u16, timeout: Duration, engine: Option<&MutChild>) -> bool {
    let deadline = Instant::now() + timeout;
    while Instant::now() < deadline {
        if TcpStream::connect((Ipv4Addr::LOCALHOST, port)).is_ok() {
            return true;
        }
        if let Some(child) = engine {
            let alive = child.lock().expect("engine lock").as_mut()
                .map(|c| c.try_wait().map(|r| r.is_none()).unwrap_or(true))
                .unwrap_or(true);
            if !alive {
                return false;
            }
        }
        std::thread::sleep(Duration::from_millis(300));
    }
    false
}

type MutChild = Mutex<Option<Child>>;

/// Locate the bundled cc-connect binary next to this app's executable.
fn sidecar_path() -> PathBuf {
    let name = format!("cc-connect{}", std::env::consts::EXE_SUFFIX);
    if let Ok(exe) = std::env::current_exe() {
        let dir = exe.parent().expect("exe dir");
        for c in [dir.join("binaries").join(&name), dir.join(&name)] {
            if c.exists() {
                return c;
            }
        }
    }
    PathBuf::from(&name)
}

/// Run a script through the user's interactive login zsh and return the last
/// non-empty stdout line. `-i` is required: version managers (nvm, pyenv,
/// sdkman) hook their PATH into `.zshrc`, which a non-interactive `zsh -lc`
/// never reads, so their CLIs stay invisible. `.zshrc` may print noise, so
/// callers consume only the final line.
fn zsh_login_last_line(script: &str) -> Option<String> {
    let out = Command::new("/bin/zsh")
        .arg("-ilc")
        .arg(script)
        .output()
        .ok()?;
    if !out.status.success() {
        return None;
    }
    String::from_utf8_lossy(&out.stdout)
        .lines()
        .rev()
        .map(str::trim)
        .find(|l| !l.is_empty())
        .map(str::to_string)
}

/// GUI apps get a minimal PATH that misses homebrew/nvm agent CLIs. Rebuild it
/// from a zsh login shell (macOS user rc) before spawning the engine so the
/// engine (and the agent CLIs it manages) inherit a usable PATH.
fn fix_path_from_login_shell() {
    if let Some(p) = zsh_login_last_line("printf %s \"$PATH\"").filter(|p| p.contains('/')) {
        std::env::set_var("PATH", p);
        return;
    }
    // Fallback for setups whose interactive zsh fails under the GUI env.
    if let Ok(out) = Command::new("/bin/zsh").arg("-lc").arg("printf %s \"$PATH\"").output() {
        if out.status.success() && !out.stdout.is_empty() {
            std::env::set_var("PATH", String::from_utf8_lossy(&out.stdout).to_string());
        }
    }
}

/// Spawn the cc-connect engine pointed at the app's config, logging to log_path.
fn start_engine(config_path: &std::path::Path, log_path: &std::path::Path) -> Result<Child, String> {
    // App data dir may not exist on first launch; create it before opening the log.
    if let Some(parent) = log_path.parent() {
        std::fs::create_dir_all(parent).map_err(|e| format!("create app dir: {e}"))?;
    }
    let bin = sidecar_path();
    let log = std::fs::OpenOptions::new()
        .create(true)
        .append(true)
        .open(log_path)
        .map_err(|e| format!("open engine log {}: {e}", log_path.display()))?;
    let err = log.try_clone().map_err(|e| format!("clone log fd: {e}"))?;
    Command::new(&bin)
        .arg("--config")
        .arg(config_path)
        // Per-config lock: if a previous shell process was hard-killed and
        // left an orphan engine behind, the next launch reaps it.
        .arg("--force")
        .stdout(Stdio::from(log))
        .stderr(Stdio::from(err))
        .spawn()
        .map_err(|e| format!("spawn {}: {e}", bin.display()))
        .inspect(|c| ENGINE_PID.store(c.id(), std::sync::atomic::Ordering::Relaxed))
}

/// Kill the running engine if any; leaving it running would clash on the web port.
fn kill_engine(engine: &Engine) {
    if let Some(mut child) = engine.child.lock().expect("engine lock").take() {
        clear_reaper_pid();
        let _ = child.kill();
        let _ = child.wait();
    }
}

/// Login URL for the engine's web admin, using fresh port/token from config.
fn engine_login_url(config_path: &std::path::Path) -> Url {
    let (port, token) = read_management(config_path);
    let mut url: Url = format!("http://127.0.0.1:{port}/login").parse().expect("login url");
    if let Some(token) = token {
        url.query_pairs_mut().append_pair("token", &token);
    }
    url
}

/// Full (re)start cycle: spawn engine, wait for the web port, point main window at it.
fn restart_engine(app: &AppHandle, config_path: &std::path::Path, log_path: &std::path::Path) -> Result<(), String> {
    let engine: State<Engine> = app.state();
    kill_engine(&engine);
    for attempt in 0..2u8 {
        let child = start_engine(config_path, log_path)?;
        *engine.child.lock().expect("engine lock") = Some(child);
        let (port, _) = read_management(config_path);
        let timeout = if attempt == 0 { FAST_START_TIMEOUT } else { ENGINE_START_TIMEOUT };
        if wait_for_port(port, timeout, Some(&engine.child)) {
            break;
        }
        if attempt == 0 {
            kill_engine(&engine);
        } else {
            return Err(format!("cc-connect web UI not reachable on port {port}"));
        }
    }
    if let Some(win) = app.get_webview_window("main") {
        let url = engine_login_url(config_path);
        let _ = win.navigate(url);
        let _ = win.set_focus();
    }
    Ok(())
}

/// Open (or navigate) the main window at the engine's web UI.
fn ensure_main_window(app: &AppHandle, config_path: &std::path::Path) -> Result<(), String> {
    let url = engine_login_url(config_path);
    if let Some(win) = app.get_webview_window("main") {
        let _ = win.show();
        let _ = win.navigate(url);
        let _ = win.set_focus();
        return Ok(());
    }
    WebviewWindowBuilder::new(app, "main", WebviewUrl::External(url))
        .title("CC Connect")
        .inner_size(1280.0, 860.0)
        .build()
        .map(|_| ())
        .map_err(|e| e.to_string())
}

/// Open (or focus) the config editor window.
fn open_editor(app: &AppHandle) {
    if let Some(w) = app.get_webview_window("editor") {
        let _ = w.set_focus();
    } else if let Err(e) = WebviewWindowBuilder::new(app, "editor", WebviewUrl::App("editor.html".into()))
        .title("Config / 配置")
        .inner_size(760.0, 620.0)
        .build()
    {
        eprintln!("failed to open editor window: {e}");
    }
}

#[tauri::command]
fn config_path(paths: State<ConfigPaths>) -> String {
    paths.config.display().to_string()
}

#[tauri::command]
fn read_config(paths: State<ConfigPaths>) -> String {
    std::fs::read_to_string(&paths.config).unwrap_or_default()
}

/// Validate + persist the edited config. Atomic: parse first, then temp-write + rename.
#[tauri::command]
fn write_config(paths: State<ConfigPaths>, content: String) -> Result<(), String> {
    toml::from_str::<toml::Value>(&content)
        .map_err(|e| format!("TOML 解析失败: {e}"))?;
    if let Some(dir) = paths.config.parent() {
        std::fs::create_dir_all(dir).map_err(|e| format!("create dir: {e}"))?;
    }
    let tmp = paths.config.with_extension("toml.tmp");
    std::fs::write(&tmp, content.as_bytes()).map_err(|e| format!("write: {e}"))?;
    std::fs::rename(&tmp, &paths.config).map_err(|e| format!("rename: {e}"))?;
    Ok(())
}

/// Agent kinds selectable in the config editor: kind → (agent `type`, default CLI binary).
/// Mirrors agent/*/New() defaults (ParseCmdOpts fallback) in the Go code.
const AGENTS: &[(&str, &str, &str)] = &[
    ("claudecode", "claudecode", "claude"),
    ("codex", "codex", "codex"),
    ("gemini", "gemini", "gemini"),
    ("cursor", "cursor", "agent"),
    ("copilot", "copilot", "copilot"),
    ("qoder", "qoder", "qodercli"),
    ("comate", "comate", "comatecli"),
    ("opencode", "opencode", "opencode"),
    ("iflow", "iflow", "iflow"),
    ("kimi", "kimi", "kimi"),
    ("antigravity", "antigravity", "agy"),
    ("pi", "pi", "pi"),
    ("devin", "devin", "devin"),
];

/// Switch the first project's agent to the selected kind, persist, restart engine.
/// Missing CLI is NOT fatal here — the frontend's check_cli shows a hint and the
/// user can still fill the full path in the config editor.
#[tauri::command]
fn set_agent(kind: String, app: AppHandle, paths: State<ConfigPaths>) -> Result<(), String> {
    let (_, agent_type, cmd) = AGENTS
        .iter()
        .find(|(k, _, _)| *k == kind)
        .ok_or_else(|| format!("未知 agent 类型: {kind}"))?;

    let content = std::fs::read_to_string(&paths.config)
        .map_err(|e| format!("read config: {e}"))?;
    let mut doc = content
        .parse::<DocumentMut>()
        .map_err(|e| format!("TOML 解析失败: {e}"))?;
    switch_agent_doc(&mut doc, agent_type, cmd)?;
    std::fs::write(&paths.config, doc.to_string()).map_err(|e| format!("write: {e}"))?;
    restart_engine(&app, &paths.config, &paths.log)?;
    // The picker is the first-run entry point: show the main UI once a real
    // agent is applied so the user lands in the actual app.
    ensure_main_window(&app, &paths.config)
}

/// Rewire the first [[projects]] agent tables to {type, options.cmd}, preserving
/// comments/formatting (toml_edit).
fn switch_agent_doc(doc: &mut DocumentMut, agent_type: &str, cmd: &str) -> Result<(), String> {
    let projects = doc
        .get_mut("projects")
        .and_then(|p| p.as_array_of_tables_mut())
        .ok_or("配置缺少 [[projects]]")?;
    let first = projects.get_mut(0).ok_or("配置缺少 [[projects]]")?;
    first["agent"]["type"] = toml_edit::value(agent_type);
    first["agent"]["options"]["cmd"] = toml_edit::value(cmd);
    Ok(())
}

#[tauri::command]
fn restart_service(app: AppHandle, paths: State<ConfigPaths>) -> Result<(), String> {
    restart_engine(&app, &paths.config, &paths.log)?;
    ensure_main_window(&app, &paths.config)
}

/// Fetch (and clear) the stored startup error, if any.
#[tauri::command]
fn take_startup_error(err: State<StartupError>) -> Option<String> {
    err.0.lock().expect("startup error lock").take()
}

/// Resolve a CLI name via the user's interactive login env (sees nvm/pyenv
/// bins that plain `zsh -lc` misses).
#[tauri::command]
fn check_cli(cmd: String) -> Result<String, String> {
    if cmd.is_empty() || !cmd.chars().all(|c| c.is_ascii_alphanumeric() || matches!(c, '.' | '_' | '-')) {
        return Err("非法 CLI 名称".to_string());
    }
    zsh_login_last_line(&format!("command -v -- {}", cmd))
        .filter(|p| p.starts_with('/'))
        .ok_or_else(|| format!("未找到 {} CLI,请先安装(pnpm/global/homebrew)", cmd))
}

/// Stop the engine, run its self-update (`cc-connect update` downloads and
/// replaces the sidecar binary), then start the engine again. Mirrors the
/// update split in ADR-0003: the shell only orchestrates stop → update → start.
/// Note: rewriting the sidecar binary inside a signed .app breaks its code
/// signature; if that ever matters, ship whole-app updates instead.
#[tauri::command]
fn engine_update(app: AppHandle, paths: State<ConfigPaths>) -> Result<String, String> {
    let engine: State<Engine> = app.state();
    kill_engine(&engine);
    let out = Command::new(sidecar_path())
        .arg("update")
        .output()
        .map_err(|e| format!("无法运行更新命令: {e}"))?;
    let mut text = String::from_utf8_lossy(&out.stdout).to_string();
    text.push_str(&String::from_utf8_lossy(&out.stderr));
    // Restart the service either way so it never stays down after a failed update.
    restart_engine(&app, &paths.config, &paths.log)?;
    if out.status.success() {
        Ok(text.trim().to_string())
    } else {
        Err(text.trim().to_string())
    }
}

fn main() {
    fix_path_from_login_shell();
    register_reaper();
    tauri::Builder::default()
        .setup(|app| {
            app.manage(Engine {
                child: Mutex::new(None),
            });
            app.manage(StartupError(StdMutex::new(None)));
            let config_path = app.path().app_config_dir()?.join("config.toml");
            let log_path = app.path().app_config_dir()?.join("engine.log");
            app.manage(ConfigPaths {
                config: config_path.clone(),
                log: log_path.clone(),
            });
            let first_run = write_default_config_if_missing(&config_path) || agent_is_stub(&config_path);

            // Menu: main UI, config editor, quit.
            let main_item = MenuItemBuilder::with_id("main-window", "Open Main UI / 打开主界面").build(app)?;
            let config_item =
                MenuItemBuilder::with_id("config-editor", "Config Editor / 配置编辑").build(app)?;
            let quit_item = MenuItemBuilder::with_id("quit", "Quit / 退出").build(app)?;
            let menu = MenuBuilder::new(app)
                .item(&main_item)
                .item(&config_item)
                .item(&quit_item)
                .build()?;
            app.set_menu(menu)?;
            let handle = app.handle().clone();
            app.on_menu_event(move |app, event| match event.id().as_ref() {
                "main-window" => {
                    let paths = app.state::<ConfigPaths>();
                    let _ = ensure_main_window(app, &paths.config);
                }
                "config-editor" => open_editor(app),
                "quit" => app.exit(0),
                _ => {}
            });

            // Tray: keep the app resident in the menu bar. Reuses the app-menu
            // item ids above so one on_menu_event handler serves both menus.
            let tray_show = MenuItemBuilder::with_id("main-window", "打开主界面 / Open").build(app)?;
            let tray_config = MenuItemBuilder::with_id("config-editor", "配置编辑 / Config").build(app)?;
            let tray_quit = MenuItemBuilder::with_id("quit", "退出 / Quit").build(app)?;
            let tray_menu = MenuBuilder::new(app)
                .items(&[&tray_show, &tray_config, &tray_quit])
                .build()?;
            TrayIconBuilder::new()
                .icon(tauri::include_image!("icons/icon.png"))
                .menu(&tray_menu)
                .tooltip("CC Connect")
                .build(app)?;

            // Start the engine; when its web UI is serving, open the main window
            // at the login URL. On failure open the editor pre-filled with an error.
            match restart_engine(&handle, &config_path, &log_path) {
                Ok(()) if app.get_webview_window("main").is_none() => {
                    if first_run {
                        // No real agent CLI picked yet: land on the picker instead.
                        open_editor(&handle);
                    } else {
                        let url = engine_login_url(&config_path);
                        WebviewWindowBuilder::new(&handle, "main", WebviewUrl::External(url))
                            .title("CC Connect")
                            .inner_size(1280.0, 860.0)
                            .build()?;
                    }
                }
                Ok(()) => {}
                Err(e) => {
                    eprintln!("engine failed to start: {e}");
                    *app.state::<StartupError>().0.lock().expect("startup error lock") = Some(e);
                    open_editor(&handle);
                }
            }
            Ok(())
        })
        .on_window_event(|window, event| {
            if let WindowEvent::CloseRequested { api, .. } = event {
                // Hide the main window to tray instead of quitting — the engine
                // keeps serving. The editor window closes normally; the shell
                // stays resident either way (see ExitRequested below).
                if window.label() == "main" {
                    api.prevent_close();
                    let _ = window.hide();
                }
            }
        })
        .invoke_handler(tauri::generate_handler![
            config_path,
            read_config,
            write_config,
            restart_service,
            take_startup_error,
            check_cli,
            set_agent,
            engine_update
        ])
        .build(tauri::generate_context!())
        .expect("error while building tauri application")
        .run(|app_handle, event| {
            match event {
                // Explicit quit (menu 退出 → app.exit) carries Some(code): stop the
                // engine so it never outlives the shell as an orphan on the web
                // port. code == None means the last window was closed (e.g. the
                // editor while the main window hides in the tray) — stay resident.
                tauri::RunEvent::ExitRequested { code, api, .. } => {
                    if code.is_none() {
                        api.prevent_exit();
                    } else {
                        kill_engine(&app_handle.state::<Engine>());
                    }
                }
                // macOS: dock icon click while resident in the tray.
                #[cfg(target_os = "macos")]
                tauri::RunEvent::Reopen { .. } => {
                    let paths = app_handle.state::<ConfigPaths>();
                    let _ = ensure_main_window(app_handle, &paths.config);
                }
                _ => {}
            }
        });
}

